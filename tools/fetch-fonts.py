#!/usr/bin/env python3
"""Downloads the webfonts, subsets them for prose, and writes their @font-face rules.

Google's CSS API serves *basic Latin only* for these families — 227 glyphs, no macron,
no double acute — while the full fonts in the google/fonts repo carry all of Latin. That
is why the ō in Paddō kept falling back to a system serif. So: take the full font, keep
the Latin ranges prose needs, and ship one woff2 per face.

Usage: python3 tools/fetch-fonts.py
"""
from pathlib import Path
import subprocess
import sys
import urllib.request

from fontTools.ttLib import TTFont

REPO = 'https://raw.githubusercontent.com/google/fonts/main/ofl'
CACHE = Path('.cache/fonts-src')
OUT = Path('public/fonts')

FACES = [
    ('young-serif', 'youngserif/YoungSerif-Regular.ttf', 'Young Serif', 'normal', '400'),
    ('source-serif-4', 'sourceserif4/SourceSerif4[opsz,wght].ttf', 'Source Serif 4', 'normal', '200 900'),
    ('source-serif-4-italic', 'sourceserif4/SourceSerif4-Italic[opsz,wght].ttf', 'Source Serif 4', 'italic', '200 900'),
]

# Latin-1, Latin Extended A/B, punctuation, symbols that show up in prose.
UNICODES = 'U+0000-024F,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20A0-20CF,U+2100-214F,U+2190-21FF,U+2200-22FF,U+FEFF,U+FFFD'

CACHE.mkdir(parents=True, exist_ok=True)
OUT.mkdir(parents=True, exist_ok=True)

rules = []
for slug, path, family, style, weight in FACES:
    source = CACHE / Path(path).name.replace('[', '-').replace(']', '')
    if not source.exists():
        print(f'downloading {path}')
        urllib.request.urlretrieve(f'{REPO}/{path}', source)

    target = OUT / f'{slug}.woff2'
    subprocess.run(
        [
            sys.executable, '-m', 'fontTools.subset', str(source),
            f'--unicodes={UNICODES}',
            '--layout-features=kern,liga,onum,tnum',
            '--flavor=woff2',
            f'--output-file={target}',
        ],
        check=True,
        capture_output=True,
    )

    coverage = TTFont(target).getBestCmap()
    missing = [c for c in 'ōőű' if ord(c) not in coverage]
    print(f'{target.name:36} {target.stat().st_size:>8} bytes  glyphs={len(coverage)}  missing={"".join(missing) or "none"}')

    rules.append(
        f"""
@font-face {{
  font-family: '{family}';
  font-style: {style};
  font-weight: {weight};
  font-display: swap;
  src: url('/fonts/{target.name}') format('woff2');
}}"""
    )

css = '/* Self-hosted webfonts. Generated by tools/fetch-fonts.py — do not edit. */\n' + ''.join(rules) + '\n'
Path('src/web/styles/fonts.css').write_text(css, encoding='utf-8')
print(f'wrote src/web/styles/fonts.css with {len(rules)} faces')
