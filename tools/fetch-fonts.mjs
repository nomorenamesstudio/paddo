/**
 * Downloads the self-hosted webfonts and writes their @font-face rules.
 *
 * Google's CSS splits each family into unicode-range subsets and *declares* narrow
 * ranges, but the "latin" file in practice carries all of Latin — macrons, double
 * acutes, everything. Keeping the declared ranges makes the browser refuse those
 * glyphs anyway (ō is U+014D, outside the declared latin range) and fall back to a
 * system serif, which is visible in the wordmark. So: one file per face, no range.
 *
 * Usage: node tools/fetch-fonts.mjs
 */
import { mkdir, writeFile } from 'node:fs/promises'

const UA =
  'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36'

const FAMILIES = [
  { css: 'family=Young+Serif&display=swap', slug: 'young-serif', family: 'Young Serif' },
  {
    css: 'family=Source+Serif+4:ital,opsz,wght@0,8..60,200..900;1,8..60,200..900&display=swap',
    slug: 'source-serif-4',
    family: 'Source Serif 4',
  },
]

/** The subset Google calls "latin": it also holds the extended Latin we need. */
const SUBSET = { match: /^U\+0000-00FF/ }

async function cssFor(query) {
  const response = await fetch(`https://fonts.googleapis.com/css2?${query}`, {
    headers: { 'user-agent': UA },
  })
  if (!response.ok) throw new Error(`Google Fonts returned ${response.status} for ${query}`)
  return response.text()
}

function blocks(css) {
  return css
    .split('@font-face')
    .slice(1)
    .map((chunk) => chunk.slice(0, chunk.indexOf('}')))
}

const rules = []
await mkdir('public/fonts', { recursive: true })

for (const family of FAMILIES) {
  const css = await cssFor(family.css)

  for (const block of blocks(css)) {
    const url = block.match(/url\((https:[^)]+\.woff2)\)/)?.[1]
    const range = block.match(/unicode-range:\s*([^;]+);/)?.[1]?.replace(/\s+/g, ' ').trim()
    const style = block.match(/font-style:\s*([^;]+);/)?.[1]?.trim() ?? 'normal'
    const weight = block.match(/font-weight:\s*([^;]+);/)?.[1]?.trim() ?? '400'
    if (!url || !range) continue

    if (!SUBSET.match.test(range)) continue

    const file = `${family.slug}${style === 'italic' ? '-italic' : ''}.woff2`
    const bytes = Buffer.from(await (await fetch(url, { headers: { 'user-agent': UA } })).arrayBuffer())
    await writeFile(`public/fonts/${file}`, bytes)
    console.log(`${file.padEnd(42)} ${String(bytes.length).padStart(7)} bytes`)

    rules.push({ family: family.family, style, weight, file })
  }
}

const css = [
  '/* Self-hosted webfonts. Generated by tools/fetch-fonts.mjs — do not edit. */',
  ...rules.map(
    (rule) => `
@font-face {
  font-family: '${rule.family}';
  font-style: ${rule.style};
  font-weight: ${rule.weight};
  font-display: swap;
  src: url('/fonts/${rule.file}') format('woff2');
}`,
  ),
  '',
].join('\n')

await writeFile('src/web/styles/fonts.css', css)
console.log(`\nwrote src/web/styles/fonts.css with ${rules.length} faces`)
