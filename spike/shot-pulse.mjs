import { readFile } from 'node:fs/promises'
import { chromium } from '@playwright/test'
const env = Object.fromEntries((await readFile(new URL('../.env', import.meta.url), 'utf8'))
  .split('\n').filter((l) => l.includes('=')).map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]))
const browser = await chromium.launch()
const page = await (await browser.newContext({ viewport: { width: 1180, height: 700 }, deviceScaleFactor: 2 })).newPage()
await page.goto('http://127.0.0.1:4319/')
await page.locator('input[type="password"]').fill(env.PADDO_PASSWORD)
await page.getByRole('button', { name: /open padd/i }).click()
await page.locator('.documents').waitFor()
await page.goto('http://127.0.0.1:4319/d/the-ghosted-story')
await page.locator('.skeleton').waitFor({ timeout: 5000 })
const read = () => page.evaluate(() => [...document.querySelectorAll('.skeleton__line')].map((l) => Number(getComputedStyle(l).opacity).toFixed(2)))
const a = await read()
await page.screenshot({ path: 'screenshots/skeleton-a.png', clip: { x: 150, y: 60, width: 880, height: 260 } })
await page.waitForTimeout(380)
const b = await read()
await page.screenshot({ path: 'screenshots/skeleton-b.png', clip: { x: 150, y: 60, width: 880, height: 260 } })
await page.waitForTimeout(380)
const c = await read()
console.log(JSON.stringify({ a, b, c }))
await browser.close()
