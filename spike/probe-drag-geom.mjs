import { readFile } from 'node:fs/promises'
import { chromium } from '@playwright/test'
const env = Object.fromEntries((await readFile(new URL('../.env', import.meta.url), 'utf8'))
  .split('\n').filter((l) => l.includes('=')).map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]))
const browser = await chromium.launch()
const page = await (await browser.newContext({ viewport: { width: 1280, height: 720 } })).newPage()
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
await page.goto('http://127.0.0.1:4319/')
await page.locator('input[type="password"]').fill(env.PADDO_PASSWORD)
await page.getByRole('button', { name: /open padd/i }).click()
await page.locator('.documents').waitFor()
const slug = await page.evaluate(async () => (await (await fetch('/api/documents', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ name: 'Drag probe' }) })).json()).slug)
await page.goto(`http://127.0.0.1:4319/d/${slug}`)
await page.locator('.prose h1').waitFor()
await page.waitForTimeout(1200)
await page.locator('.prose p').last().click()
await page.keyboard.type('First block stays here.')
await page.keyboard.press('Enter')
await page.keyboard.type('Second block should move up.')
await page.waitForTimeout(800)

const geom = await page.evaluate(() => {
  const bar = document.querySelector('.topbar').getBoundingClientRect()
  const first = document.querySelectorAll('.prose > p')[0].getBoundingClientRect()
  const second = document.querySelectorAll('.prose > p')[1].getBoundingClientRect()
  return { bar: { top: bar.top, bottom: bar.bottom }, first: { top: first.top, bottom: first.bottom }, second: { top: second.top } }
})
await page.locator('.prose > p').nth(1).hover()
const grip = await page.locator('.grip').boundingBox()
await page.mouse.move(grip.x + grip.width / 2, grip.y + grip.height / 2)
await page.mouse.down()
await page.mouse.move(geom.first.top && 500, geom.first.top + 4, { steps: 10 })
await page.waitForTimeout(300)
const draggingAtTopEdge = await page.locator('.prose .is-dragging').count()
await page.mouse.move(500, geom.first.top + geom.first.bottom / 2, { steps: 6 })
await page.waitForTimeout(300)
const draggingAtMid = await page.locator('.prose .is-dragging').count()
await page.mouse.up()
await page.evaluate((target) => fetch(`/api/documents/${target}`, { method: 'DELETE' }), slug)
console.log(JSON.stringify({ geom, grip, draggingAtTopEdge, draggingAtMid, errors }))
await browser.close()
